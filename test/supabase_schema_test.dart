import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:matchup/core/db/app_database.dart';
import 'package:matchup/core/sync/sync_outbox.dart';
import 'package:matchup/core/sync/sync_tables.dart';
import 'package:sqflite_common_ffi/sqflite_ffi.dart';

/// `supabase/schema.sql` is generated from the phone's own tables (lib/core/sync/sync_tables.dart),
/// so Supabase always has the same columns. After adding a table or a column:
///
///     flutter test test/supabase_schema_test.dart --update-goldens
///
/// then run supabase/schema.sql in the Supabase SQL editor (it can be run again safely).
void main() {
  test('supabase/schema.sql matches the synced tables', () async {
    sqfliteFfiInit();
    final database = AppDatabase(factory: databaseFactoryFfi, path: inMemoryDatabasePath);
    addTearDown(database.close);
    final db = await database.db;

    final out = StringBuffer()
      ..writeln('-- Generated by test/supabase_schema_test.dart from lib/core/sync/sync_tables.dart.')
      ..writeln('-- Do not edit: add the table there, run the test with --update-goldens, then run this')
      ..writeln('-- whole file in the Supabase SQL editor (safe to run again).')
      ..writeln();
    for (final t in syncTables) {
      final s = await tableShape(db, t.name);
      String type(String c) => switch (s.types[c]) {
            'INTEGER' => 'bigint',
            'REAL' => 'double precision',
            'BLOB' => 'bytea',
            _ => 'text',
          };
      out
        ..writeln('-- ${t.name} (${t.scope.name})')
        ..writeln('create table if not exists public.${t.name} (')
        ..writeln('  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,');
      for (final c in s.columns) {
        out.writeln('  "$c" ${type(c)}${s.notNull.contains(c) ? ' not null' : ''},');
      }
      out
        ..writeln('  primary key (owner_id, ${s.keys.map((k) => '"$k"').join(', ')})')
        ..writeln(');');
      for (final c in s.columns) {
        out.writeln('alter table public.${t.name} add column if not exists "$c" ${type(c)};');
      }
      out
        ..writeln('alter table public.${t.name} enable row level security;')
        ..writeln('drop policy if exists "${t.name}_lecture" on public.${t.name};')
        ..writeln('drop policy if exists "${t.name}_ecriture" on public.${t.name};')
        ..writeln(
          t.scope == SyncScope.shared
              ? 'create policy "${t.name}_lecture" on public.${t.name} for select to authenticated using (true);'
              : 'create policy "${t.name}_lecture" on public.${t.name} for select to authenticated using (owner_id = auth.uid());',
        )
        ..writeln(
          'create policy "${t.name}_ecriture" on public.${t.name} for all to authenticated '
          'using (owner_id = auth.uid()) with check (owner_id = auth.uid()'
          '${t.ownerColumn == null ? '' : ' and "${t.ownerColumn}" = auth.uid()::text'});',
        )
        ..writeln();
    }

    final file = File('supabase/schema.sql');
    final sql = out.toString();
    if (autoUpdateGoldenFiles) {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(sql);
    }
    expect(file.existsSync() ? file.readAsStringSync().replaceAll('\r\n', '\n') : '', sql,
        reason: 'Run: flutter test test/supabase_schema_test.dart --update-goldens');
  });
}
