def gen_type(T):
    ty = T['type']
    fam_method = {}
    for key, stack in ty['families'].items():
        m = re.match(r'\s*"([^"]+)"', stack)
        if not m:
            raise TokenError(f'type.families.{key}: first family must be quoted, got {stack!r}')
        fam_method[key] = (m.group(1), ident(m.group(1)))
    arabic_key = 'arabic' if 'arabic' in fam_method else None

    L = [HEADER, '//', '// MatchUp type styles. Families come from the google_fonts package.', '',
         "import 'dart:ui' show FontFeature, TextLeadingDistribution;", '',
         "import 'package:flutter/material.dart';", "import 'package:google_fonts/google_fonts.dart';", '',
         '/// One [TextStyle] per type style in tokens.json, sizes and line heights exactly as specified.',
         '///',
         '/// Styles carry no colour: they inherit `DefaultTextStyle` (which MuTheme sets to `text`), or add',
         "/// one with `copyWith(color: context.mu.textSecondary)`. Pick the style with the right weight instead",
         '/// of changing `fontWeight` (google_fonts loads one file per weight).',
         '/// `height` is lineHeight / fontSize; leading is split evenly above and below, as on the web.',
         'abstract final class MuType {']
    styles = {}
    for g in ty['groups']:
        fam_key = g['family']
        family, method = fam_method[fam_key]
        tabular = fam_key == 'numeric'
        L.append(f'  // ---- {g["name"]} · {family} ' + '-' * max(4, 60 - len(g['name']) - len(family)))
        if g.get('note'):
            L.append(doc(g['note'], '  // ').replace('/// ', '', 1))
        L.append('')
        for s in g['styles']:
            n = s['name']
            f = ident(n)
            if f in styles:
                raise TokenError(f'type style {n!r} collides with another style ({f})')
            fs = px(s['fontSize'], n)
            lh = px(s['lineHeight'], n)
            fw = int(s['fontWeight'])
            if fw % 100 or not 100 <= fw <= 900:
                raise TokenError(f'{n}: font weight {fw} is not 100…900')
            args = [f'fontSize: {num(fs)}', f'height: {int(lh) if lh.is_integer() else num(lh)} / {int(fs) if fs.is_integer() else num(fs)}',
                    f'fontWeight: FontWeight.w{fw}']
            ls_note = ''
            # letterSpacing is always explicit: a null would inherit Material's tracking (0.1–0.5).
            if not s.get('letterSpacing'):
                args.append('letterSpacing: 0.0')
            else:
                m = re.fullmatch(r'\s*(-?[\d.]+)(em|px)\s*', s['letterSpacing'])
                if not m:
                    raise TokenError(f'{n}: letterSpacing {s["letterSpacing"]!r} is not em or px')
                ls = float(m.group(1)) * (fs if m.group(2) == 'em' else 1)
                args.append(f'letterSpacing: {num(round(ls, 4))}')
                ls_note = f' · {s["letterSpacing"]}'
            args.append('leadingDistribution: TextLeadingDistribution.even')
            if tabular:
                args.append('fontFeatures: <FontFeature>[FontFeature.tabularFigures()]')
            styles[n] = (f, method, fam_key)
            L.append(f'  static const TextStyle _{f} = TextStyle(')
            for a in args:
                L.append(f'    {a},')
            L.append('  );')
            L.append('')
            spec = f'{s["fontSize"]}/{s["lineHeight"]} · {fw}{ls_note}'
            L.append(doc(f'`{n}` — {family} {spec}. {s.get("usage", "")}'))
            if 'uppercase' in s.get('usage', '').lower():
                L.append('  ///')
                L.append('  /// Uppercase is applied at use, not by the style: `Text(label.toUpperCase(), style: MuType.'
                         f'{f})`.')
            if tabular:
                L.append('  ///')
                L.append('  /// Tabular figures (`FontFeature.tabularFigures()`), so digits never jump while they change.')
            L.append(f'  static final TextStyle {f} = GoogleFonts.{method}(textStyle: _{f});')
            L.append('')

    # Material text themes
    for slot, st in TEXT_THEME_SLOTS:
        if st not in styles:
            raise TokenError(f'TextTheme slot {slot} needs type style {st!r}, which is missing')
    fallbacks = []
    if arabic_key:
        _, ar_method = fam_method[arabic_key]
        for slot, st in TEXT_THEME_SLOTS:
            if f'ar-{st}' not in styles and st not in fallbacks:
                fallbacks.append(st)
        if fallbacks:
            L.append('  // Interface styles with no ar-* counterpart: same metrics, Arabic family.')
            for st in fallbacks:
                f = styles[st][0]
                L.append(f'  static final TextStyle _{f}Arabic = GoogleFonts.{ar_method}(textStyle: _{f});')
            L.append('')
    L += ['  /// The Material [TextTheme] built from these styles (colours are added by MuTheme).',
          '  ///',
          '  /// Mapping: display → display*, h1 → displaySmall/headlineLarge, h2 → headlineMedium/Small,',
          '  /// h3 → titleLarge, label-l → titleMedium, label → titleSmall/labelLarge (buttons, chips, tabs),',
          '  /// body-l/body/caption → bodyLarge/Medium/Small, label-s → labelMedium/labelSmall (tab bar).',
          '  /// With [arabic] the slots use the ar-* styles (IBM Plex Sans Arabic, taller lines); styles with',
          '  /// no Arabic counterpart keep their metrics in the Arabic family. Numerals are not in the',
          '  /// TextTheme: use [numM], [numS]… directly (digits stay Western in every locale).',
          '  static TextTheme textTheme({bool arabic = false}) {']
    if arabic_key:
        L.append('    if (arabic) {')
        L.append('      return TextTheme(')
        for slot, st in TEXT_THEME_SLOTS:
            if f'ar-{st}' in styles:
                L.append(f'        {slot}: {styles["ar-" + st][0]},')
            else:
                L.append(f'        {slot}: _{styles[st][0]}Arabic,')
        L += ['      );', '    }']
    L.append('    return TextTheme(')
    for slot, st in TEXT_THEME_SLOTS:
        L.append(f'      {slot}: {styles[st][0]},')
    L += ['    );', '  }', '}', '']
    return '\n'.join(L), {v[0] for v in styles.values()}


