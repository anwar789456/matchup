def gen_theme(color_fields, type_fields, elevation_fields, T):
    charts = sorted([f for f in color_fields if re.fullmatch(r'chart\d+', f)], key=lambda f: int(f[5:]))
    if not charts:
        raise TokenError('no chart-<n> colour tokens')
    values = '\n'.join(f'  {f}{";" if i == len(charts) - 1 else ","}' for i, f in enumerate(charts))
    cases = '\n'.join(f'        MuChartColor.{f} => c.{f},' for f in charts)
    src = (THEME_DART.replace('@@HEADER@@', HEADER)
           .replace('@@CHART_VALUES@@', values)
           .replace('@@CHART_CASES@@', cases))

    # Drift guard: every token-backed name the template uses must exist.
    refs = {
        r'\b(?:c|other|colors)\.([a-z][A-Za-z0-9]*)\b': (color_fields, 'MuColors field'),
        r'\bMuType\.([a-z][A-Za-z0-9]*)\b': (type_fields | {'textTheme'}, 'MuType style'),
        r'\be\.([a-z][A-Za-z0-9]*)\b': (elevation_fields | {'shadowColor'}, 'MuElevation field'),
    }
    for pattern, (known, what) in refs.items():
        for name in sorted(set(re.findall(pattern, src))):
            if name not in known:
                raise TokenError(f'mu_theme.dart uses {what} {name!r}, which tokens.json does not define')
    statics = {
        'MuSpace': {f's{re.fullmatch(r"space-(\d+)", t["name"]).group(1)}' for t in T['spacing']['tokens']},
        'MuSize': {ident(t['name']) for t in T['size']['tokens']},
        'MuOpacity': {ident(t['name'], 'opacity-') for t in T['opacity']['tokens']},
        'MuMotion': {ident(t['name'], 'duration-') for t in T['duration']['tokens']}
        | {ident(t['name'], 'ease-') for t in T['easing']['tokens']},
        'MuRadius': {ident(t['name'], 'radius-') + 'All' for t in T['radius']['tokens']} | {'lgTop'},
    }
    for cls, known in statics.items():
        for name in sorted(set(re.findall(rf'\b{cls}\.([a-z][A-Za-z0-9]*)\b', src))):
            if name not in known:
                raise TokenError(f'mu_theme.dart uses {cls}.{name}, which tokens.json does not define')
    return src


