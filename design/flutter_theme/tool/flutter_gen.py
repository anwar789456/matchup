def main():
    T = json.load(open(TOKENS, encoding='utf-8'))
    C = Colors(T)
    tokens_src, elevation_fields = gen_tokens(T, C)
    colors_src, color_fields = gen_colors(C)
    type_src, type_fields = gen_type(T)
    theme_src = gen_theme(color_fields, type_fields, elevation_fields, T)
    os.makedirs(OUT, exist_ok=True)
