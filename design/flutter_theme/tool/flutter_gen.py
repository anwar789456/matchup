"""Generate the Flutter theme (flutter/lib/theme/*.dart) from tokens/tokens.json.

Every value in the Dart files comes from tokens.json, so Flutter can never drift from the
web previews: colours are resolved per theme (aliases followed), CSS lengths, durations,
cubic-beziers, box-shadows and linear-gradients are parsed into their Flutter types.
The component themes in mu_theme.dart only reference generated names; the generator checks
every `c.<colour>`, `MuSize.<x>`, `MuSpace.<x>`… reference against the tokens and fails if
a token it relies on disappears or is renamed.

usage: python3 tools/flutter_gen.py            (writes flutter/lib/theme/)
       python3 flutter_gen.py tokens.json ../lib/theme   (inside the Flutter package)
"""
import json
import math
import os
import re
import sys
from collections import Counter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
# Optional arguments: python3 flutter_gen.py [path/to/tokens.json] [output/dir]
TOKENS = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(ROOT, 'tokens', 'tokens.json')
OUT = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else os.path.join(ROOT, 'flutter', 'lib', 'theme')
HEADER = '// GENERATED by tools/flutter_gen.py from tokens/tokens.json — do not edit by hand.'

DART_RESERVED = set('''assert break case catch class const continue default do else enum extends
false final finally for if in is new null rethrow return super switch this throw true try var
void while with type hashCode runtimeType toString copyWith lerp of'''.split())


class TokenError(Exception):
    pass


# ---------------------------------------------------------------------------- helpers

def camel(name):
    """'on-primary' → 'onPrimary', 'ink-900' → 'ink900', 'IBM Plex Sans Arabic' → 'ibmPlexSansArabic'."""
    parts = [p for p in re.split(r'[-_\s]+', name) if p]
    if not parts:
        raise TokenError(f'empty name: {name!r}')
    out = parts[0].lower() + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.match(r'^[a-z][A-Za-z0-9]*$', out):
        raise TokenError(f'cannot make a Dart identifier from {name!r} ({out!r})')
    return out


def ident(name, strip_prefix=None):
    n = name
    if strip_prefix and n.startswith(strip_prefix):
        n = n[len(strip_prefix):]
    out = camel(n)
    if out in DART_RESERVED:
        raise TokenError(f'token {name!r} maps to the reserved Dart name {out!r}')
    return out


def num(x):
    """Dart double literal: 4 → '4.0', 0.98 → '0.98'."""
    x = float(x)
    if x == 0:
        return '0.0'
    if x.is_integer():
        return f'{int(x)}.0'
    return repr(round(x, 6))


def px(value, where):
    m = re.fullmatch(r'\s*(-?[\d.]+)\s*(px)?\s*', str(value))
    if not m:
        raise TokenError(f'{where}: expected a px length, got {value!r}')
    return float(m.group(1))


def doc(text, indent='  '):
    text = ' '.join(str(text).split())
    return f'{indent}/// {text}' if text else ''


HEX_RE = re.compile(r'^#([0-9a-fA-F]{3}|[0-9a-fA-F]{4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$')


def hex_parts(h, where):
    if not isinstance(h, str) or not HEX_RE.match(h):
        raise TokenError(f'{where}: expected a #hex colour, got {h!r}')
    s = h[1:].lower()
    if len(s) in (3, 4):
        s = ''.join(ch * 2 for ch in s)
    if len(s) == 6:
        s += 'ff'
    return s[:6], s[6:]


def dart_color(h, where='colour'):
    rgb, a = hex_parts(h, where)
    return f'Color(0x{a.upper()}{rgb.upper()})'


def is_alias(v):
    return isinstance(v, str) and v.startswith('{') and v.endswith('}')


# ---------------------------------------------------------------------------- colours

class Colors:
    def __init__(self, T):
        self.themes = [t['id'] for t in T['color']['themes']]
        if self.themes[:2] != ['light', 'dark']:
            raise TokenError(f'expected themes light + dark, got {self.themes}')
        self.tokens = T['color']['tokens']
        self.by = {t['name']: t for t in self.tokens}
        names = [ident(t['name']) for t in self.tokens]
        dup = [n for n, k in Counter(names).items() if k > 1]
        if dup:
            raise TokenError(f'colour tokens collide after camelCase: {dup}')

    def raw(self, name, th):
        if name not in self.by:
            raise TokenError(f'unknown colour token {name!r}')
        v = self.by[name]['value']
        if isinstance(v, dict):
            v = v.get(th, v.get(self.themes[0]))
        return v

    def constant(self, name, seen=()):
        """Same value in every theme: a plain value, or an alias to a constant token."""
        if name in seen:
            raise TokenError(f'alias cycle: {" → ".join(seen + (name,))}')
        v = self.by[name]['value']
        if isinstance(v, dict):
            return False
        if is_alias(v):
            return self.constant(v[1:-1], seen + (name,))
        return True

    def hex(self, name, th, seen=()):
        if name in seen:
            raise TokenError(f'alias cycle: {" → ".join(seen + (name,))}')
        v = self.raw(name, th)
        if is_alias(v):
            return self.hex(v[1:-1], th, seen + (name,))
        hex_parts(v, f'color.{name}.{th}')
        return v.lower()

    def palette_expr(self, name):
        """Initialiser of a MuPalette constant (refers to the aliased constant when it is one)."""
        v = self.by[name]['value']
        if is_alias(v):
            return ident(v[1:-1])
        return dart_color(v, f'color.{name}')

    def theme_expr(self, name, th):
        """Initialiser of a MuColors field for one theme."""
        if self.constant(name):
            return f'MuPalette.{ident(name)}'
        v = self.raw(name, th)
        if is_alias(v):
            target = v[1:-1]
            if self.constant(target):
                return f'MuPalette.{ident(target)}'
            return self.theme_expr(target, th)
        return dart_color(v, f'color.{name}.{th}')


# ---------------------------------------------------------------------------- shadows & gradients

SHADOW_RE = re.compile(
    r'^(?P<inset>inset\s+)?(?P<x>-?[\d.]+)(?:px)?\s+(?P<y>-?[\d.]+)(?:px)?'
    r'(?:\s+(?P<blur>-?[\d.]+)(?:px)?)?(?:\s+(?P<spread>-?[\d.]+)(?:px)?)?\s+(?P<color>#[0-9a-fA-F]+)$')


def parse_shadows(value, where):
    out = []
    for part in [p.strip() for p in value.split(',') if p.strip()]:
        m = SHADOW_RE.match(part)
        if not m:
            raise TokenError(f'{where}: cannot parse box-shadow part {part!r}')
        if m.group('inset'):
            raise TokenError(f'{where}: inset shadows have no BoxShadow equivalent ({part!r})')
        out.append({
            'x': float(m.group('x')), 'y': float(m.group('y')),
            'blur': float(m.group('blur') or 0), 'spread': float(m.group('spread') or 0),
            'color': m.group('color'),
        })
    # CSS paints the FIRST shadow on top; BoxDecoration paints the list in order (last on top).
    return list(reversed(out))


def box_shadow(s, where):
    args = [f'color: {dart_color(s["color"], where)}']
    if s['x'] or s['y']:
        args.append(f'offset: Offset({num(s["x"])}, {num(s["y"])})')
    if s['blur']:
        args.append(f'blurRadius: {num(s["blur"])}')
    if s['spread']:
        args.append(f'spreadRadius: {num(s["spread"])}')
    return f'BoxShadow({", ".join(args)})'


GRAD_RE = re.compile(r'^linear-gradient\(\s*(?P<angle>-?[\d.]+)deg\s*,(?P<stops>.+)\)$')
STOP_RE = re.compile(r'^(?P<color>#[0-9a-fA-F]+)\s+(?P<pos>[\d.]+)%$')

NAMED_ALIGN = {
    (0, -1): 'Alignment.topCenter', (0, 1): 'Alignment.bottomCenter',
    (-1, 0): 'Alignment.centerLeft', (1, 0): 'Alignment.centerRight',
    (-1, -1): 'Alignment.topLeft', (1, 1): 'Alignment.bottomRight',
    (1, -1): 'Alignment.topRight', (-1, 1): 'Alignment.bottomLeft',
}


def alignment(x, y):
    x, y = round(x, 6) + 0.0, round(y, 6) + 0.0
    key = (int(x), int(y)) if x.is_integer() and y.is_integer() else None
    if key in NAMED_ALIGN:
        return NAMED_ALIGN[key]
    return f'Alignment({num(x)}, {num(y)})'


def parse_gradient(value, where):
    m = GRAD_RE.match(value.strip())
    if not m:
        raise TokenError(f'{where}: only linear-gradient(<deg>, <#hex> <n>%, …) is supported, got {value!r}')
    deg = float(m.group('angle'))
    stops = []
    for part in [p.strip() for p in m.group('stops').split(',')]:
        sm = STOP_RE.match(part)
        if not sm:
            raise TokenError(f'{where}: cannot parse colour stop {part!r}')
        stops.append((sm.group('color').lower(), float(sm.group('pos')) / 100))
    # CSS angle: 0deg points up, 90deg right. Flutter: begin/end Alignments on the box.
    a = math.radians(deg)
    dx, dy = math.sin(a), -math.cos(a)
    k = max(abs(dx), abs(dy))
    ex, ey = dx / k, dy / k
    return deg, alignment(-ex, -ey), alignment(ex, ey), stops


# ---------------------------------------------------------------------------- generation

def gen_tokens(T, C):
    L = [HEADER, '//', '// MatchUp design tokens — constant primitives, the same in Light and Night match.',
         '// Themed colours are in mu_colors.dart (MuColors); type styles in mu_type.dart (MuType).',
         '', "import 'package:flutter/material.dart';", '']

    # MuPalette
    L += ['/// Colour tokens whose value is the same in Light and Night match (aliases resolved).',
          '///',
          '/// Prefer the semantic roles on `MuColors` (`context.mu.text`, `context.mu.primary`…) in widgets;',
          '/// reach for the palette only where a role does not exist (illustrations, painters).',
          'abstract final class MuPalette {']
    palette = [t for t in C.tokens if C.constant(t['name'])]
    for t in palette:
        L.append(doc(f'`{t["name"]}` {C.hex(t["name"], "light")} — {t.get("usage", "")}'))
        L.append(f'  static const Color {ident(t["name"])} = {C.palette_expr(t["name"])};')
        L.append('')
    L[-1:] = ['}', '']

    # MuSpace
    sp = T['spacing']
    L += [f'/// Spacing scale. {sp.get("note", "")}'.rstrip(), 'abstract final class MuSpace {']
    for t in sp['tokens']:
        m = re.fullmatch(r'space-(\d+)', t['name'])
        if not m:
            raise TokenError(f'spacing token {t["name"]!r} is not space-<n>')
        L.append(doc(f'`{t["name"]}` {t["value"]} — {t.get("usage", "")}'))
        L.append(f'  static const double s{m.group(1)} = {num(px(t["value"], t["name"]))};')
        L.append('')
    L[-1:] = ['}', '']

    # MuRadius
    rd = T['radius']
    L += [f'/// Corner radii. {rd.get("note", "")}'.rstrip(), 'abstract final class MuRadius {']
    rnames = []
    for t in rd['tokens']:
        n = ident(t['name'], 'radius-')
        rnames.append(n)
        L.append(doc(f'`{t["name"]}` {t["value"]} — {t.get("usage", "")}'))
        L.append(f'  static const double {n} = {num(px(t["value"], t["name"]))};')
        L.append('')
    for n in rnames:
        L.append(doc(f'`BorderRadius.circular({n})` on every corner.'))
        L.append(f'  static const BorderRadius {n}All = BorderRadius.all(Radius.circular({n}));')
        L.append('')
    if 'lg' in rnames:
        L.append(doc('Top corners only at `radius-lg` — bottom sheets.'))
        L.append('  static const BorderRadius lgTop = BorderRadius.vertical(top: Radius.circular(lg));')
        L.append('')
    L[-1:] = ['}', '']

    # MuSize
    sz = T['size']
    L += [f'/// Sizes. {sz.get("note", "")} Percentages are fractions of the screen (0–1).'.rstrip(),
          'abstract final class MuSize {']
    for t in sz['tokens']:
        v = str(t['value']).strip()
        if v.endswith('%'):
            val = num(float(v[:-1]) / 100)
        else:
            val = num(px(v, t['name']))
        L.append(doc(f'`{t["name"]}` {v} — {t.get("usage", "")}'))
        L.append(f'  static const double {ident(t["name"])} = {val};')
        L.append('')
    L[-1:] = ['}', '']

    # MuLayout
    ly = T['layout']
    L += [f'/// Grid and breakpoints. {ly.get("note", "")}'.rstrip(), 'abstract final class MuLayout {']
    for t in ly['tokens']:
        v = str(t['value']).strip()
        L.append(doc(f'`{t["name"]}` {v} — {t.get("usage", "")}'))
        if re.fullmatch(r'\d+', v):
            L.append(f'  static const int {ident(t["name"])} = {v};')
        else:
            L.append(f'  static const double {ident(t["name"])} = {num(px(v, t["name"]))};')
        L.append('')
    L[-1:] = ['}', '']

    # MuMotion
    du = T['duration']
    L += [f'/// Motion. {du.get("note", "")}'.rstrip(),
          '///',
          '/// Reduced motion: wrap every duration in [durationOf] (it returns zero when the user asked the',
          '/// system to remove animations) and stop looping pulses and shimmers.',
          'abstract final class MuMotion {']
    for t in du['tokens']:
        m = re.fullmatch(r'\s*([\d.]+)\s*(ms|s)\s*', str(t['value']))
        if not m:
            raise TokenError(f'{t["name"]}: expected ms or s, got {t["value"]!r}')
        ms = float(m.group(1)) * (1000 if m.group(2) == 's' else 1)
        if not ms.is_integer():
            raise TokenError(f'{t["name"]}: sub-millisecond duration {t["value"]!r}')
        L.append(doc(f'`{t["name"]}` {t["value"]} — {t.get("usage", "")}'))
        L.append(f'  static const Duration {ident(t["name"], "duration-")} = Duration(milliseconds: {int(ms)});')
        L.append('')
    for t in T['easing']['tokens']:
        m = re.fullmatch(r'\s*cubic-bezier\(\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*\)\s*',
                         str(t['value']))
        if not m:
            raise TokenError(f'{t["name"]}: expected cubic-bezier(a, b, c, d), got {t["value"]!r}')
        a, b, c, d = (num(g) for g in m.groups())
        L.append(doc(f'`{t["name"]}` {t["value"]} — {t.get("usage", "")}'))
        L.append(f'  static const Curve {ident(t["name"], "ease-")} = Cubic({a}, {b}, {c}, {d});')
        L.append('')
    for t in T['scale']['tokens']:
        n = t['name']
        name = ident('-'.join(reversed(n.split('-', 1)))) if n.startswith('scale-') else ident(n)
        L.append(doc(f'`{n}` {t["value"]} — {t.get("usage", "")} Use with `AnimatedScale`.'))
        L.append(f'  static const double {name} = {num(t["value"])};')
        L.append('')
    L += ['  /// [duration], or [Duration.zero] when the platform asks to remove animations',
          '  /// (`MediaQuery.disableAnimationsOf`).',
          '  static Duration durationOf(BuildContext context, Duration duration) =>',
          '      MediaQuery.disableAnimationsOf(context) ? Duration.zero : duration;',
          '}', '']

    # MuOpacity
    L += ['/// Opacity steps (use with `Color.withValues(alpha: …)`).', 'abstract final class MuOpacity {']
    for t in T['opacity']['tokens']:
        L.append(doc(f'`{t["name"]}` {t["value"]} — {t.get("usage", "")}'))
        L.append(f'  static const double {ident(t["name"], "opacity-")} = {num(t["value"])};')
        L.append('')
    L[-1:] = ['}', '']

    # MuGradients
    L += ['/// Gradients. CSS angles are physical, so these are not mirrored in RTL.',
          'abstract final class MuGradients {']
    for t in T['gradient']['tokens']:
        n = t['name']
        name = ident(n.replace('-gradient', '')) if '-gradient' in n else ident(n)
        deg, begin, end, stops = parse_gradient(t['value'], n)
        colors = [dart_color(h, n) for h, _ in stops]
        frm, to = f'{n}-from', f'{n}-to'
        if frm in C.by and to in C.by and len(stops) == 2:
            for (h, _), tok in zip(stops, (frm, to)):
                if not C.constant(tok) or C.hex(tok, 'light') != h:
                    raise TokenError(f'{n}: stop {h} disagrees with colour token {tok} '
                                     f'({C.hex(tok, "light")}) — fix tokens.json')
            colors = [f'MuPalette.{ident(frm)}', f'MuPalette.{ident(to)}']
        L.append(doc(f'`{n}` {t["value"]} — {t.get("usage", "")}'))
        L.append(f'  static const LinearGradient {name} = LinearGradient(')
        L.append(f'    begin: {begin},')
        L.append(f'    end: {end},')
        L.append(f'    colors: <Color>[{", ".join(colors)}],')
        L.append(f'    stops: <double>[{", ".join(num(p) for _, p in stops)}],')
        L.append('  );')
        L.append('')
    L[-1:] = ['}', '']

    # MuElevation
    sh = T['shadow']
    per = {}
    for t in sh['tokens']:
        n = t['name']
        field = ident('level-' + n[len('elevation-'):]) if n.startswith('elevation-') else ident(n)
        per[field] = t
    for th in ('light', 'dark'):
        for f, t in per.items():
            v = t['value'][th] if isinstance(t['value'], dict) else t['value']
            parse_shadows(v, f'{t["name"]}.{th}')

    def shadow_color(th):
        rgbs = Counter()
        for t in sh['tokens']:
            v = t['value'][th] if isinstance(t['value'], dict) else t['value']
            for s in parse_shadows(v, t['name']):
                if s['blur'] > 0:
                    rgbs[hex_parts(s['color'], t['name'])[0]] += 1
        if not rgbs:
            raise TokenError(f'no soft shadow in theme {th}')
        return dart_color('#' + rgbs.most_common(1)[0][0])

    L += [f'/// Shadows per theme, parsed from the CSS box-shadow tokens. {sh.get("note", "")}'.rstrip(),
          '///',
          '/// Lists are in Flutter paint order (CSS paints its first shadow on top, so the order is reversed).',
          '/// Use them in a `BoxDecoration(boxShadow: MuElevation.of(context).level2)`; for Material widgets',
          '/// that only take a number, use [materialLevel1]…[materialLevel3] and the theme\'s hairline [ringOf].',
          '@immutable',
          'final class MuElevation {',
          '  const MuElevation._({']
    for f in per:
        L.append(f'    required this.{f},')
    L += ['    required this.shadowColor,', '  });', '']
    for f, t in per.items():
        L.append(doc(f'`{t["name"]}` — {t.get("usage", "")}'))
        L.append(f'  final List<BoxShadow> {f};')
        L.append('')
    L += ['  /// Opaque base colour of this theme\'s soft shadows (`ColorScheme.shadow`).',
          '  final Color shadowColor;', '']
    for th, label in (('light', 'Light'), ('dark', 'Night match')):
        L.append(f'  /// {label}.')
        L.append(f'  static const MuElevation {th} = MuElevation._(')
        for f, t in per.items():
            v = t['value'][th] if isinstance(t['value'], dict) else t['value']
            L.append(f'    // {v}')
            L.append(f'    {f}: <BoxShadow>[')
            for s in parse_shadows(v, t['name']):
                L.append(f'      {box_shadow(s, t["name"])},')
            L.append('    ],')
        L.append(f'    shadowColor: {shadow_color(th)},')
        L.append('  );')
        L.append('')
    levels = [f for f in ('level1', 'level2', 'level3') if f in per]
    approx = {'level1': '1.0', 'level2': '3.0', 'level3': '6.0'}
    for f in levels:
        L.append(f'  /// Closest Material `elevation` to `{per[f]["name"]}`, for widgets that only take a number.')
        L.append(f'  static const double material{f[0].upper() + f[1:]} = {approx[f]};')
        L.append('')
    L += ['  /// The shadows of the current theme (by `Theme.of(context).brightness`).',
          '  static MuElevation of(BuildContext context) =>',
          '      Theme.of(context).brightness == Brightness.dark ? dark : light;',
          '',
          '  /// The hairline ring (`0 0 0 <n>px`) inside [shadows] as a [BorderSide], or null when there is',
          '  /// none. Night match draws elevation as a ring + lighter surface; Light has no ring.',
          '  static BorderSide? ringOf(List<BoxShadow> shadows) {',
          '    for (final BoxShadow s in shadows) {',
          '      if (s.offset == Offset.zero && s.blurRadius == 0 && s.spreadRadius > 0) {',
          '        return BorderSide(color: s.color, width: s.spreadRadius);',
          '      }',
          '    }',
          '    return null;',
          '  }',
          '}', '']
    return '\n'.join(L), set(per)


def gen_colors(C):
    fields = [(t, ident(t['name'])) for t in C.tokens]
    L = [HEADER, '//', '// MatchUp colours as a ThemeExtension: one field per colour token, Light and Night match.',
         '', "import 'package:flutter/material.dart';", '', "import 'mu_tokens.dart';", '',
         '/// Every MatchUp colour token, resolved for one theme.',
         '///',
         '/// Read it with `context.mu` (see `MuThemeX` in mu_theme.dart) or [MuColors.of]:',
         '/// ```dart',
         '/// final colors = context.mu;',
         '/// ColoredBox(color: colors.surfaceMuted);',
         '/// ```',
         'class MuColors extends ThemeExtension<MuColors> {',
         '  /// Creates a colour set. Use [light] or [dark]; build your own only for tests.',
         '  const MuColors({']
    for _, f in fields:
        L.append(f'    required this.{f},')
    L += ['  });', '']
    for t, f in fields:
        lh, dh = C.hex(t['name'], 'light'), C.hex(t['name'], 'dark')
        vals = lh if lh == dh else f'Light {lh} · Night match {dh}'
        L.append(doc(f'`{t["name"]}` ({vals}) — {t.get("usage", "")}'))
        L.append(f'  final Color {f};')
        L.append('')
    for th, label in (('light', 'Light'), ('dark', 'Night match')):
        L.append(f'  /// « {label} ».')
        L.append(f'  static const MuColors {th} = MuColors(')
        for t, f in fields:
            L.append(f'    {f}: {C.theme_expr(t["name"], th)},')
        L.append('  );')
        L.append('')
    L += ['  /// The colours of the current theme; falls back to [light] / [dark] by brightness when the',
          '  /// ThemeData was not built by MuTheme.',
          '  static MuColors of(BuildContext context) {',
          '    final ThemeData theme = Theme.of(context);',
          '    return theme.extension<MuColors>() ?? (theme.brightness == Brightness.dark ? dark : light);',
          '  }',
          '',
          '  @override',
          '  MuColors copyWith({']
    for _, f in fields:
        L.append(f'    Color? {f},')
    L += ['  }) {', '    return MuColors(']
    for _, f in fields:
        L.append(f'      {f}: {f} ?? this.{f},')
    L += ['    );', '  }', '',
          '  @override',
          '  MuColors lerp(ThemeExtension<MuColors>? other, double t) {',
          '    if (other is! MuColors) {',
          '      return this;',
          '    }',
          '    return MuColors(']
    for _, f in fields:
        L.append(f'      {f}: Color.lerp({f}, other.{f}, t)!,')
    L += ['    );', '  }', '}', '']
